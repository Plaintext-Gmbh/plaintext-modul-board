-- Karte 2193: Board-Tabellen (Kanban ersetzt Nextcloud-Deck). Spalten wie SuperModel
-- (Muster plaintext-modul-zeiterfassung): Audit + MANDAT + TAGS je Zeile.
CREATE TABLE IF NOT EXISTS board (
  ID BIGSERIAL,
  CREATED_BY VARCHAR(255),
  CREATED_DATE TIMESTAMP,
  DELETED BOOLEAN,
  LAST_MODIFIED_BY VARCHAR(255),
  LAST_MODIFIED_DATE TIMESTAMP,
  MANDAT VARCHAR(255),
  TAGS VARCHAR(5000),
  TITLE VARCHAR(255),
  PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS board_stack (
  ID BIGSERIAL,
  CREATED_BY VARCHAR(255),
  CREATED_DATE TIMESTAMP,
  DELETED BOOLEAN,
  LAST_MODIFIED_BY VARCHAR(255),
  LAST_MODIFIED_DATE TIMESTAMP,
  MANDAT VARCHAR(255),
  TAGS VARCHAR(5000),
  BOARD_ID BIGINT,
  TITLE VARCHAR(255),
  SORT_INDEX INTEGER NOT NULL,
  WIP_LIMIT INTEGER,
  PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS board_label (
  ID BIGSERIAL,
  CREATED_BY VARCHAR(255),
  CREATED_DATE TIMESTAMP,
  DELETED BOOLEAN,
  LAST_MODIFIED_BY VARCHAR(255),
  LAST_MODIFIED_DATE TIMESTAMP,
  MANDAT VARCHAR(255),
  TAGS VARCHAR(5000),
  BOARD_ID BIGINT,
  TITLE VARCHAR(255),
  COLOR VARCHAR(255),
  PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS board_card (
  ID BIGSERIAL,
  CREATED_BY VARCHAR(255),
  CREATED_DATE TIMESTAMP,
  DELETED BOOLEAN,
  LAST_MODIFIED_BY VARCHAR(255),
  LAST_MODIFIED_DATE TIMESTAMP,
  MANDAT VARCHAR(255),
  TAGS VARCHAR(5000),
  BOARD_ID BIGINT,
  STACK_ID BIGINT,
  TITLE VARCHAR(255),
  DESCRIPTION VARCHAR(100000),
  SORT_INDEX INTEGER NOT NULL,
  DUE_DATE TIMESTAMP,
  ARCHIVED BOOLEAN,
  PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS board_card_labels (
  BOARD_CARD_ID BIGINT NOT NULL,
  LABELS_ID BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS board_card_assigned_user_ids (
  BOARD_CARD_ID BIGINT NOT NULL,
  ASSIGNED_USER_IDS BIGINT
);

CREATE TABLE IF NOT EXISTS board_comment (
  ID BIGSERIAL,
  CREATED_BY VARCHAR(255),
  CREATED_DATE TIMESTAMP,
  DELETED BOOLEAN,
  LAST_MODIFIED_BY VARCHAR(255),
  LAST_MODIFIED_DATE TIMESTAMP,
  MANDAT VARCHAR(255),
  TAGS VARCHAR(5000),
  CARD_ID BIGINT,
  MESSAGE VARCHAR(100000),
  ACTOR_ID VARCHAR(255),
  ACTOR_DISPLAY_NAME VARCHAR(255),
  PRIMARY KEY (ID)
);
